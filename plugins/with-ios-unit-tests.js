const {
  withDangerousMod,
  withPodfile,
  withXcodeProject,
} = require("@expo/config-plugins");
const fs = require("fs");
const path = require("path");

const TEST_TARGET = "ScanLockTests";
const TEST_SOURCE_DIRECTORY = path.join("native-tests", "ios");
const PODFILE_MARKER = "# ScanLock XCTest target (generated by with-ios-unit-tests)";

function unquote(value) {
  return typeof value === "string" ? value.replace(/^"|"$/g, "") : value;
}

function findApplicationTarget(project) {
  const targets = project.pbxNativeTargetSection();
  for (const [uuid, target] of Object.entries(targets)) {
    if (uuid.endsWith("_comment")) continue;
    if (unquote(target.productType) === "com.apple.product-type.application") {
      return { uuid, target, name: unquote(target.name) };
    }
  }
  throw new Error("Unable to find the generated iOS application target.");
}

function findTarget(project, name) {
  const targets = project.pbxNativeTargetSection();
  for (const [uuid, target] of Object.entries(targets)) {
    if (uuid.endsWith("_comment")) continue;
    if (unquote(target.name) === name) return { uuid, target };
  }
  return null;
}

function removeTargetDependency(project, ownerUuid, dependencyUuid) {
  const owner = project.pbxNativeTargetSection()[ownerUuid];
  const dependencies = project.hash.project.objects.PBXTargetDependency || {};
  const proxies = project.hash.project.objects.PBXContainerItemProxy || {};

  owner.dependencies = (owner.dependencies || []).filter((reference) => {
    const dependency = dependencies[reference.value];
    if (!dependency || dependency.target !== dependencyUuid) return true;

    const proxyUuid = dependency.targetProxy;
    delete dependencies[reference.value];
    delete dependencies[`${reference.value}_comment`];
    if (proxyUuid) {
      delete proxies[proxyUuid];
      delete proxies[`${proxyUuid}_comment`];
    }
    return false;
  });
}

function configureTestBuildSettings(project, testTarget, bundleIdentifier) {
  const configurationList = project.pbxXCConfigurationList()[
    testTarget.target.buildConfigurationList
  ];
  const configurations = project.pbxXCBuildConfigurationSection();

  for (const reference of configurationList.buildConfigurations) {
    const settings = configurations[reference.value].buildSettings;
    delete settings.INFOPLIST_FILE;
    settings.GENERATE_INFOPLIST_FILE = "YES";
    settings.IPHONEOS_DEPLOYMENT_TARGET = "16.0";
    settings.PRODUCT_BUNDLE_IDENTIFIER = `"${bundleIdentifier}.tests"`;
    settings.SWIFT_VERSION = "5.0";
    delete settings.TEST_HOST;
    delete settings.BUNDLE_LOADER;
    settings.TARGETED_DEVICE_FAMILY = '"1,2"';
  }
}

function listSwiftFiles(directory) {
  const results = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) results.push(...listSwiftFiles(fullPath));
    if (entry.isFile() && entry.name.endsWith(".swift")) results.push(fullPath);
  }
  return results;
}

function addTestTarget(config) {
  return withXcodeProject(config, (mod) => {
    const project = mod.modResults;
    if (findTarget(project, TEST_TARGET)) return mod;

    const appTarget = findApplicationTarget(project);
    const bundleIdentifier = mod.ios?.bundleIdentifier;
    if (!bundleIdentifier) {
      throw new Error("ios.bundleIdentifier is required for the XCTest target.");
    }

    const testTarget = project.addTarget(
      TEST_TARGET,
      "unit_test_bundle",
      TEST_TARGET,
      `${bundleIdentifier}.tests`
    );

    // xcode's helper may create app -> test. These are non-hosted module tests,
    // so neither target should depend on the other.
    removeTargetDependency(project, appTarget.uuid, testTarget.uuid);

    project.addBuildPhase([], "PBXSourcesBuildPhase", "Sources", testTarget.uuid);
    project.addBuildPhase([], "PBXFrameworksBuildPhase", "Frameworks", testTarget.uuid);
    project.addBuildPhase([], "PBXResourcesBuildPhase", "Resources", testTarget.uuid);

    const group = project.addPbxGroup([], TEST_TARGET, TEST_TARGET);
    const mainGroupUuid = project.getFirstProject().firstProject.mainGroup;
    project.addToPbxGroup(group.uuid, mainGroupUuid);

    const sourceRoot = path.join(mod.modRequest.projectRoot, TEST_SOURCE_DIRECTORY);
    for (const sourcePath of listSwiftFiles(sourceRoot)) {
      project.addSourceFile(
        path.basename(sourcePath),
        { target: testTarget.uuid },
        group.uuid
      );
    }

    const target = { uuid: testTarget.uuid, target: testTarget.pbxNativeTarget };
    configureTestBuildSettings(project, target, bundleIdentifier);
    createSharedScheme(
      mod.modRequest.projectRoot,
      mod.modRequest.projectName,
      appTarget,
      target
    );
    return mod;
  });
}

function copyDirectoryContents(source, destination) {
  fs.rmSync(destination, { recursive: true, force: true });
  fs.mkdirSync(destination, { recursive: true });
  for (const sourcePath of listSwiftFiles(source)) {
    fs.copyFileSync(sourcePath, path.join(destination, path.basename(sourcePath)));
  }
}

function addPodfileTestTarget(podfile, appTargetName) {
  if (podfile.includes(PODFILE_MARKER)) return podfile;

  const appTargetStart = `target '${appTargetName}' do`;
  const appTargetIndex = podfile.indexOf(appTargetStart);
  if (appTargetIndex < 0) {
    throw new Error(`Unable to find ${appTargetStart} in the generated Podfile.`);
  }

  const postInstallIndex = podfile.indexOf("  post_install do", appTargetIndex);
  if (postInstallIndex < 0) {
    throw new Error("Unable to locate post_install in the generated iOS app target.");
  }

  const testTarget = [
    `  ${PODFILE_MARKER}`,
    `  target '${TEST_TARGET}' do`,
    "    inherit! :complete",
    "  end",
    "",
  ].join("\n");
  podfile = `${podfile.slice(0, postInstallIndex)}${testTarget}${podfile.slice(postInstallIndex)}`;
  return podfile;
}

function createSharedScheme(projectRoot, projectName, appTarget, testTarget) {
  const schemeDirectory = path.join(
    projectRoot,
    "ios",
    `${projectName}.xcodeproj`,
    "xcshareddata",
    "xcschemes"
  );
  fs.mkdirSync(schemeDirectory, { recursive: true });

  const container = `container:${projectName}.xcodeproj`;
  const scheme = `<?xml version="1.0" encoding="UTF-8"?>
<Scheme LastUpgradeVersion="1600" version="1.7">
  <BuildAction parallelizeBuildables="YES" buildImplicitDependencies="YES">
    <BuildActionEntries>
      <BuildActionEntry buildForTesting="YES" buildForRunning="NO" buildForProfiling="NO" buildForArchiving="NO" buildForAnalyzing="YES">
        <BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="${testTarget.uuid}" BuildableName="${TEST_TARGET}.xctest" BlueprintName="${TEST_TARGET}" ReferencedContainer="${container}"/>
      </BuildActionEntry>
    </BuildActionEntries>
  </BuildAction>
  <TestAction buildConfiguration="Debug" selectedDebuggerIdentifier="Xcode.DebuggerFoundation.Debugger.LLDB" selectedLauncherIdentifier="Xcode.DebuggerFoundation.Launcher.LLDB" shouldUseLaunchSchemeArgsEnv="YES">
    <Testables>
      <TestableReference skipped="NO">
        <BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="${testTarget.uuid}" BuildableName="${TEST_TARGET}.xctest" BlueprintName="${TEST_TARGET}" ReferencedContainer="${container}"/>
      </TestableReference>
    </Testables>
  </TestAction>
  <LaunchAction buildConfiguration="Debug" selectedDebuggerIdentifier="Xcode.DebuggerFoundation.Debugger.LLDB" selectedLauncherIdentifier="Xcode.DebuggerFoundation.Launcher.LLDB" launchStyle="0" useCustomWorkingDirectory="NO" ignoresPersistentStateOnLaunch="NO" debugDocumentVersioning="YES" debugServiceExtension="internal" allowLocationSimulation="YES">
    <BuildableProductRunnable runnableDebuggingMode="0">
      <BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="${appTarget.uuid}" BuildableName="${appTarget.name}.app" BlueprintName="${appTarget.name}" ReferencedContainer="${container}"/>
    </BuildableProductRunnable>
  </LaunchAction>
  <ProfileAction buildConfiguration="Release" shouldUseLaunchSchemeArgsEnv="YES" savedToolIdentifier="" useCustomWorkingDirectory="NO" debugDocumentVersioning="YES"/>
  <AnalyzeAction buildConfiguration="Debug"/>
  <ArchiveAction buildConfiguration="Release" revealArchiveInOrganizer="YES"/>
</Scheme>
`;
  fs.writeFileSync(path.join(schemeDirectory, `${TEST_TARGET}.xcscheme`), scheme);
}

function copyTestSources(config) {
  return withDangerousMod(config, ["ios", (mod) => {
    const projectRoot = mod.modRequest.projectRoot;
    const sourceRoot = path.join(projectRoot, TEST_SOURCE_DIRECTORY);
    const destination = path.join(projectRoot, "ios", TEST_TARGET);
    copyDirectoryContents(sourceRoot, destination);
    return mod;
  }]);
}

function addTestPodTarget(config) {
  return withPodfile(config, (mod) => {
    mod.modResults.contents = addPodfileTestTarget(
      mod.modResults.contents,
      mod.modRequest.projectName
    );
    return mod;
  });
}

module.exports = function withIosUnitTests(config) {
  config = copyTestSources(config);
  config = addTestTarget(config);
  config = addTestPodTarget(config);
  return config;
};
